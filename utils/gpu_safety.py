"""Безопасный запуск блокирующих GPU-вызовов (rembg/CLIP) из async-кода.

08.07.2026: обнаружено, что remove_background()/clip_score() вызывались
напрямую внутри async-функций, без asyncio.to_thread — то есть выполнялись
прямо в event loop. Если видеодрайвер роняет CUDA-контекст (уже случалось:
авария Vulkan/ANGLE при конкуренции CLIP-инференса и Playwright-Chromium за
GPU), такой вызов зависает НАВСЕГДА и замораживает весь процесс бота целиком
(все чаты, все пользователи) — обычный asyncio.wait_for тут не спасает,
потому что зависшему коду некуда отдать управление обратно в луп.

run_gpu() всегда уводит вызов в отдельный поток и оборачивает его в
таймаут: поток может зависнуть сам по себе, но event loop остаётся живым,
а таск просто возвращает default вместо зависания.

17.07.2026 (по опыту второго ПК, отчёт report_20260716.md): раньше поток
уводился через asyncio.to_thread() — это ОБЩИЙ пул потоков event loop,
используемый вообще всем в боте. При таймауте поток не убивается (Python
принципиально не умеет прерывать чужой поток) — он продолжает висеть в
фоне и держит слот в общем пуле. Несколько таких зависаний подряд — и
общий пул исчерпан, весь бот (не только фотообработка) начинает вставать
в очередь. Теперь GPU-вызовы уводятся в отдельный, изолированный
ThreadPoolExecutor — зависание режет максимум эти 2 воркера, не весь бот."""
import asyncio
import functools
import logging
from concurrent.futures import ThreadPoolExecutor

log = logging.getLogger(__name__)

# 14.08.2026: было max_workers=2 — два GPU-вызова (CLIP на PyTorch/CUDA +
# rembg на onnxruntime CUDAExecutionProvider, оба дёргаются изнутри
# _score_image) реально параллелились на одной 3060 Ti без какой-либо
# блокировки между рантаймами. Тот же класс конкуренции, что раньше давал
# BFCArena::AllocateRawInternal при нехватке VRAM (см. память
# pc_hardware_hangs, п.11) — сегодня проявился зависанием потока
# ("GPU-вызов завис") вместо ошибки аллокации. Сериализуем все GPU-вызовы
# через один воркер — конкуренция за CUDA-контекст исчезает, скоринг
# кандидатов чуть медленнее, зато без спонтанных 45с-таймаутов.
_GPU_EXECUTOR = ThreadPoolExecutor(max_workers=1, thread_name_prefix="gpu")


# 14.08.2026: очередь отделена от таймаута. Раньше wait_for оборачивал
# run_in_executor целиком — таймаут тикал с момента ПОСТАНОВКИ В ОЧЕРЕДЬ,
# а не с начала выполнения. При 3 параллельных кандидатах (sem=3 в
# images.py) и реальных ~20с на один _score_image на этой машине третий
# в очереди отстаивал 40с и вылетал по 45с-таймауту, даже не начав
# выполняться — ложные "GPU-вызов завис" через одного, хорошие фото
# отбрасывались, поиск уезжал в медленный Playwright-обход (живой паттерн
# успех/таймаут/успех/таймаут в логе 11:01-11:02 14.08). Семафор равен
# числу воркеров пула: держим его — воркер гарантированно свободен, и
# wait_for меряет только само выполнение. Реально зависший поток по-прежнему
# отравляет только этот изолированный пул, не весь бот.
_GPU_SEMAPHORE = asyncio.Semaphore(_GPU_EXECUTOR._max_workers)


async def run_gpu(func, *args, timeout: float = 60, default=None, label: str = "", **kwargs):
    """Выполняет func(*args, **kwargs) в изолированном GPU-пуле потоков с
    таймаутом. При таймауте/ошибке возвращает default и логирует
    предупреждение — не бросает исключение дальше, чтобы не ронять весь
    батч из-за одного подвисшего вызова. Ожидание очереди (семафор) в
    таймаут НЕ входит — только само выполнение."""
    loop = asyncio.get_running_loop()
    call = functools.partial(func, *args, **kwargs)
    async with _GPU_SEMAPHORE:
        try:
            return await asyncio.wait_for(loop.run_in_executor(_GPU_EXECUTOR, call), timeout=timeout)
        except asyncio.TimeoutError:
            log.warning(f"GPU-вызов завис (таймаут {timeout:.0f}с, {label!r}) — считаем неудачным")
            return default
        except Exception as e:
            log.warning(f"GPU-вызов ошибка ({label!r}): {e}")
            return default
