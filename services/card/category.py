# "in" ловит их ВНУТРИ случайных слов без всякой связи по смыслу (баг
# 21.07.2026: "ram" находился внутри "DURAMO" — кроссовки Adidas Duramo RC2
# улетали в категорию "Оперативная память"). Для них — только по границе
# слова.
_SHORT_ASCII_KW = _re.compile(r"^[a-z]{1,4}$")

# 10.08.2026: однословные кириллические ключи матчились только сырой
# подстрокой — "кабель" не совпадал с "кабелей"/"кабелем" (русские падежи
# меняют хвост слова, "кабель" не подстрока "кабелей"). Живой пропуск:
# "Комплект кабелей питания Xerox ..." провалился в LLM-угадывание и не
# нашёл категорию, хотя нужная категория и ключ давно есть. Раньше такие
# пропуски чинили точечно — переименовывали ключ в укороченный корень
# ("кабель" → "кабел", "крепление" → "креплени", видно ниже по файлу) —
# рабочий, но легко забываемый приём: каждое новое слово в CATEGORY_MAP
# нужно было вручную проверять на все падежи, что и привело к сегодняшнему
# пропуску. Добавлен лёгкий стеммер как ДОПОЛНИТЕЛЬНАЯ проверка (не замена
# подстроки — старое поведение, включая уже вручную подрезанные ключи типа
# "креплени", остаётся как есть): однословные кириллические ключи ещё
# сравниваются пословно по отброшенному стандартному падежному окончанию
# (текст разбивается на кириллические слова, каждое стеммируется и
# сверяется со стеммированным ключом) — целым словом, не сырой подстрокой
# где угодно, чтобы не ловить случайные совпадения середины слова (тот же
# класс риска, что раньше был с "электро-" префиксом в отдельном
# fuzzy-матчере WB-категорий, см. wb_electro_prefix_category_bug_2026-07-30
# — там ловило именно потому, что резалось по любому месту строки).
# Многословные фразы-ключи (с пробелом) не трогаем — их поведение не
# меняется.
_RU_NOUN_SUFFIXES = sorted(
    ["иями", "ями", "ами", "ов", "ев", "ей", "ах", "ях", "ию", "ие",
     "ья", "ье", "ой", "ем", "ём", "ы", "и", "а", "я", "у", "ю", "е", "о", "ь"],
    key=len, reverse=True,
)
_CYRILLIC_WORD_RE = _re.compile(r"[а-яё]+")


def _ru_stem(word: str) -> str:
    """Грубое отбрасывание падежного окончания — не полноценная морфология
    (pymorphy и т.п. в проекте нет), но покрывает частые случаи склонений
    без лишних зависимостей. Режет ровно одно окончание из списка, самое
    длинное подходящее — достаточно для сравнения "тот же корень или нет",
    не претендует на лингвистическую точность."""
    for suf in _RU_NOUN_SUFFIXES:
        if len(word) - len(suf) >= 3 and word.endswith(suf):
            return word[: -len(suf)]
    return word


def _kw_matches(kw: str, text: str) -> bool:
    if _SHORT_ASCII_KW.match(kw):
        return _re.search(rf"(?<![a-z0-9]){_re.escape(kw)}(?![a-z0-9])", text) is not None
    if kw in text:
        return True
    if " " not in kw and _CYRILLIC_WORD_RE.fullmatch(kw):
        kw_stem = _ru_stem(kw)
        return any(_ru_stem(w) == kw_stem for w in _CYRILLIC_WORD_RE.findall(text))
    return False


# 23.07.2026: сборки ПК местных магазинов часто называются просто строкой
# характеристик ("Core i3-12100-3.3GHz/H610/RAM 8GB/SSD 512GB/no DVD/400W")
# без единого слова "компьютер"/"системный блок" — нашли живьём на артикуле
# 202628, LLM-угадывание зацепилось за "SSD" и увело в "Внутренние
# SSD-накопители". Комбинация модели CPU + RAM + накопителя + мощности БП в
# одной строке — с высокой вероятностью целая сборка, а не отдельная деталь
# (у одиночного модуля RAM/SSD в названии не бывает рядом мощности БП).
_PC_BUILD_CPU_RE = _re.compile(r"\b(core\s*i[3579]|ryzen\s*[3579])\b", _re.IGNORECASE)
_PC_BUILD_RAM_RE = _re.compile(r"\bram\b", _re.IGNORECASE)
_PC_BUILD_STORAGE_RE = _re.compile(r"\b(ssd|hdd)\b", _re.IGNORECASE)
_PC_BUILD_PSU_RE = _re.compile(r"\b\d{3,4}\s*w\b", _re.IGNORECASE)


# 13.08.2026: поставщицкие фиды ноутбуков (Lenovo ThinkPad, HP ZBook/ProBook
# и т.п.) часто начинаются сразу с модельной линейки, без слова
# "ноутбук"/"NB <бренд>" вообще — "ThinkPad T14 G6, Intel Core Ultra 5 228V
# ..., 14" WUXGA Non-Touch..., 32.0GB, 1x1TB SSD M.2 2280 PCIe Gen5...".
# Ни "ноутбук", ни "nb lenovo" не матчились, и голое "ssd" из перечня
# характеристик уводило карточку в "SSD накопители" раньше, чем
# первый-3-слова/фоллбэк-проход успевал понять, что это цельный ноутбук
# (живой случай, батч Lenovo/Dell/Acer от 13.08). Диагональ экрана в дюймах
# ("14"", "15.6"") + модель CPU (Core i/Ultra, Ryzen) + объём RAM в GB в
# одной строке — сигнатура, которой не бывает у одиночного SSD/видеокарты/
# процессора/монитора (у монитора нет CPU, у SSD/видеокарты нет диагонали
# экрана) — надёжно отличает цельный ноутбук, включая случаи без "ssd".
_LAPTOP_SCREEN_RE = _re.compile(r'\b\d{1,2}(\.\d)?\s*"', _re.IGNORECASE)
_LAPTOP_CPU_RE = _re.compile(
    r"\b(core\s*(i[3579]|ultra)|ryzen\s*(ai\s*)?[3579])\b", _re.IGNORECASE
)
_LAPTOP_RAM_RE = _re.compile(r"\b\d{1,3}(\.\d)?\s*gb\b", _re.IGNORECASE)


# 12.08.2026: живой случай в поставщицком фиде — "СPU Intel Сore Ultra 7
# 265K..." (и ещё 2 позиции) не матчились ВООБЩЕ (detect_category возвращал
# ''), хотя явно процессоры. Причина — первая буква "С" в "СPU"/"Сore"
# оказалась кириллической (U+0421), а не латинской "C" (визуально
# неотличимо, типичная порча copy-paste из источника со смешанной
# раскладкой) — ни один латинский ключ не матчился по факту иной кодовой
# точки. Слепая замена кириллица→латиница по всей строке сломала бы обычные
# русские слова ("процессор" тоже содержит с/о/р/е) — поэтому чиним только
# ТОКЕНЫ, где Latin и Cyrillic буквы перемешаны в одном "слове" (настоящие
# русские слова так не смешиваются, это надёжный сигнал порчи).
_MIXED_SCRIPT_TOKEN_RE = _re.compile(r"[a-zа-яё]+", _re.IGNORECASE)
_CYRILLIC_HOMOGLYPH_TRANS = str.maketrans({
    "а": "a", "в": "b", "е": "e", "к": "k", "м": "m", "н": "h", "о": "o",
    "р": "p", "с": "c", "т": "t", "у": "y", "х": "x",
})


def _fix_mixed_script_homoglyphs(text: str) -> str:
    def _fix(m: "_re.Match") -> str:
        tok = m.group()
        has_latin = any("a" <= c <= "z" for c in tok)
        has_cyrillic = any("а" <= c <= "я" or c == "ё" for c in tok)
        return tok.translate(_CYRILLIC_HOMOGLYPH_TRANS) if has_latin and has_cyrillic else tok
    return _MIXED_SCRIPT_TOKEN_RE.sub(_fix, text)


# 13.08.2026: официальные спецификации Lenovo/Intel вставляют ®/™/© прямо
# между словами без пробела ("Core™ Ultra 5", "Intel®BE201") — из-за этого
# "core\s*ultra" и подобные regex-и (_PC_BUILD_CPU_RE, _LAPTOP_CPU_RE) не
# стыковались, хотя визуально это одно и то же "Core Ultra". Вырезаем эти
# символы целиком до всех остальных проверок — они не несут смысловой
# нагрузки для определения категории.
_TRADEMARK_SYMBOL_RE = _re.compile(r"[®™©]")


def detect_category(raw_name: str) -> str:
    """Определяет категорию товара по названию."""
    lower = _fix_mixed_script_homoglyphs(_TRADEMARK_SYMBOL_RE.sub("", raw_name.lower()))

    # Сохранённые правила пользователя — приоритет
    for key, cat in _load_json(CATEGORY_RULES_FILE).items():
        if _kw_matches(key, lower):
            return cat

    if (_PC_BUILD_CPU_RE.search(lower) and _PC_BUILD_RAM_RE.search(lower)
            and _PC_BUILD_STORAGE_RE.search(lower) and _PC_BUILD_PSU_RE.search(lower)):
        return "Компьютеры"

    if (_LAPTOP_SCREEN_RE.search(lower) and _LAPTOP_CPU_RE.search(lower)
            and _LAPTOP_RAM_RE.search(lower)):
        return "Ноутбуки"

    # Первые 3 слова — категория чаще стоит в начале
    first = " ".join(lower.split()[:3])
    for kw, cat in CATEGORY_MAP.items():
        if _kw_matches(kw, first):
            return cat

    # Вся строка — фоллбэк
    for kw, cat in CATEGORY_MAP.items():
        if _kw_matches(kw, lower):
            return cat

    return ""


def build_chars_prompt(category: str) -> tuple[str, bool]:
    """
    Строит промпт характеристик для категории.
    Возвращает (prompt, category_found).
    """
    if not category:
        return CHARACTERISTICS_FALLBACK, False

    fields_data = _load_json(CATEGORY_FIELDS_FILE)
    fields = fields_data.get(category, [])

    if not fields:
        return CHARACTERISTICS_FALLBACK, False

    prompt = CHARACTERISTICS_HEADER.format(
        category=category,
        fields="\n".join(fields),
    )
    return prompt, True


