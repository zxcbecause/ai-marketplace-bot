# Коды ТН ВЭД ЕАЭС по категориям — для категорий, где код практически
# всегда один и тот же (не зависит от конкретной модели товара).
# Источники: kodtnved.ru, ifcg.ru, alta.ru (актуально на 2026).
TNVED_CODES: dict[str, str] = {
    "Мыши":           "8471607000",  # устройства ввода для ВМ — мыши (вкл. беспроводные)
    "Наушники":       "8518309500",  # наушники и гарнитуры, с микрофоном или без
    "Акустика":       "8518220009",  # наборы громкоговорителей в одном корпусе (по умолчанию)
    "SSD накопители": "8523519300",  # твердотельные накопители (записываемые/перезаписываемые)
    "Камеры видеонаблюдения": "8525891900",  # телевизионные камеры, прочие
    "Комплект клавиатура и мышь": "8471606000",  # декларируется по коду клавиатуры
}


def get_tnved_code(category: str, chars: dict[str, str] | None = None) -> str | None:
    """Возвращает код ТН ВЭД для категории (10 цифр, без пробелов).

    Для «Акустика» учитывает «Количество фронтальных колонок»: если в товаре
    один динамик в корпусе — код 8518210000 (одиночный громкоговоритель),
    иначе (по умолчанию) — 8518220009 (набор громкоговорителей в корпусе).
    """
    code = TNVED_CODES.get(category)
    if category == "Акустика" and chars:
        n = (chars.get("Количество фронтальных колонок") or "").strip()
        if n.startswith("1"):
            return "8518210000"
    return code


